#!/usr/bin/env node
/**
 * Writes the generated part of both SDKs from the two files the backend
 * already generates from its own sources (and checks in CI):
 *
 *   integrations/generated/manifest.json      <- backend/src/integrations/manifest.ts
 *   frontend/public/developers/openapi.json   <- backend/src/integrations/openapi.ts
 *                                                + backend/src/developerApi/openapi.ts
 *
 * (both written by backend/scripts/integrations-generate.ts, whose --check
 * runs in .github/workflows/integrations-manifest.yml). So the chain is:
 * manifest.ts / openapi.ts -> those JSON files -> this script -> the SDKs.
 *
 * Output:
 *   packages/sdk-js/src/generated/{tools,api,helpers,version}.ts
 *   packages/sdk-python/src/kovapdf/_generated.py
 *
 *   node packages/sdk-js/scripts/generate.mjs           write them
 *   node packages/sdk-js/scripts/generate.mjs --check   compare only; exit 1 on drift (CI)
 *
 * Plain Node, no dependencies, so CI needs no install to run it.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SDK_JS = path.resolve(here, "..");
const ROOT = path.resolve(SDK_JS, "../..");
const SDK_PY = path.join(ROOT, "packages/sdk-python");

const MANIFEST_PATH = "integrations/generated/manifest.json";
const OPENAPI_PATH = "frontend/public/developers/openapi.json";

const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, MANIFEST_PATH), "utf8"));
const openapi = JSON.parse(fs.readFileSync(path.join(ROOT, OPENAPI_PATH), "utf8"));
const jsVersion = JSON.parse(fs.readFileSync(path.join(SDK_JS, "package.json"), "utf8")).version;
const pyVersion = /^version\s*=\s*"([^"]+)"/m.exec(fs.readFileSync(path.join(SDK_PY, "pyproject.toml"), "utf8"))?.[1];
if (!pyVersion) throw new Error("No version in packages/sdk-python/pyproject.toml");

const HEADER_NOTE = `Generated by packages/sdk-js/scripts/generate.mjs from ${MANIFEST_PATH} and ${OPENAPI_PATH}. Do not edit.`;
const schemas = openapi.components.schemas;
const tools = manifest.tools;

// ---------------------------------------------------------------- helpers

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^[a-z]/, (c) => c.toUpperCase());
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const kebab = (s) => snake(s).replace(/_/g, "-");
const jsdoc = (text, indent = "") => {
  if (!text) return "";
  const safe = String(text).replace(/\*\//g, "*\\/");
  return `${indent}/** ${safe} */\n`;
};
const SCHEMA_NAME = { Error: "ApiError" };
const refName = (ref) => {
  const n = ref.replace("#/components/schemas/", "");
  return SCHEMA_NAME[n] ?? n;
};
/** A tool whose id is taken by a hand-written client method gets another method name. */
const METHOD_OVERRIDE = { verify: "verify_job" };
const methodName = (id) => METHOD_OVERRIDE[id] ?? id;
const validIdent = (k) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k);

/** JSON Schema -> a TypeScript type. */
function tsType(s, indent = "") {
  if (!s || typeof s !== "object") return "unknown";
  if (s.$ref) return refName(s.$ref);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map((x) => wrapUnion(tsType(x, indent))).join(" | ");
  if (s.allOf) return s.allOf.map((x) => wrapUnion(tsType(x, indent))).join(" & ");
  if (Array.isArray(s.type)) return s.type.map((t) => tsType({ ...s, type: t }, indent)).join(" | ");
  switch (s.type) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `${wrapUnion(tsType(s.items, indent))}[]`;
    case "object": case undefined: {
      const props = s.properties ?? {};
      const keys = Object.keys(props);
      if (!keys.length) return s.additionalProperties === false ? "Record<string, never>" : "Record<string, unknown>";
      const req = new Set(s.required ?? []);
      const inner = indent + "  ";
      const lines = keys.map((k) => `${jsdoc(props[k].description, inner)}${inner}${validIdent(k) ? k : JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${tsType(props[k], inner)};`);
      if (s.additionalProperties === true) lines.push(`${inner}[key: string]: unknown;`);
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default: return "unknown";
  }
}
const wrapUnion = (t) => (/[|&]/.test(t) && !t.startsWith("{") ? `(${t})` : t);

/** A flag's kind, for the CLI. */
function optionKind(s) {
  if (s.type === "boolean") return { kind: "boolean" };
  if (s.type === "integer") return { kind: "integer" };
  if (s.type === "number") return { kind: "number" };
  if (s.type === "string") return s.enum ? { kind: "string", choices: s.enum } : { kind: "string" };
  const alts = s.anyOf ?? s.oneOf;
  if (alts && alts.every((a) => a.const !== undefined && typeof a.const === "number")) return { kind: "number", choices: alts.map((a) => a.const) };
  if (s.type === "array" && s.items?.type === "string") return s.items.enum ? { kind: "string[]", choices: s.items.enum } : { kind: "string[]" };
  return { kind: "json" };
}

function optionFields(id) {
  const sch = schemas[`JobOptions_${id}`];
  if (!sch) throw new Error(`No JobOptions_${id} in ${OPENAPI_PATH}`);
  const req = new Set(sch.required ?? []);
  return Object.entries(sch.properties ?? {}).map(([name, s]) => ({
    name, flag: kebab(name), ...optionKind(s), required: req.has(name), description: s.description ?? "", ...(s.default !== undefined ? { default: s.default } : {}),
  }));
}

/** operationId -> { method, path } from the OpenAPI paths. */
const endpoints = {};
for (const [p, ops] of Object.entries(openapi.paths)) {
  for (const [method, op] of Object.entries(ops)) {
    if (!op.operationId) continue;
    endpoints[op.operationId] = { method: method.toUpperCase(), path: p, ...(op["x-required-scope"] !== undefined ? { scope: op["x-required-scope"] } : {}) };
  }
}
const sortedEndpoints = Object.fromEntries(Object.keys(endpoints).sort().map((k) => [k, endpoints[k]]));

const toolMeta = tools.map((t) => ({
  id: t.id, command: kebab(t.id), method: camel(methodName(t.id)), title: t.title, description: t.description, scope: t.scope, limitsClass: t.limitsClass,
  inputs: t.inputs, optionsNote: t.optionsNote, options: optionFields(t.id),
}));

// ---------------------------------------------------------------- TypeScript

const files = {};
const tsHead = `// ${HEADER_NOTE}\n/* eslint-disable */\n`;

{
  let out = tsHead + "\n";
  out += `export const ATTRIBUTION = ${JSON.stringify(manifest.attribution)};\n`;
  out += `export const SITE_URL = ${JSON.stringify(manifest.server.website)};\n`;
  out += `export const API_BASE = ${JSON.stringify(manifest.server.apiBase)};\n\n`;
  out += `/** Every tool a job can run. */\nexport const TOOL_IDS = ${JSON.stringify(tools.map((t) => t.id))} as const;\nexport type ToolId = (typeof TOOL_IDS)[number];\n\n`;
  for (const t of tools) {
    const sch = schemas[`JobOptions_${t.id}`];
    out += `${jsdoc(`Options of ${t.id} (${t.title}): ${t.optionsNote}`)}export type ${pascal(t.id)}Options = ${tsType(sch)};\n\n`;
  }
  out += `/** Each tool's options. */\nexport interface ToolOptionsMap {\n${tools.map((t) => `  ${t.id}: ${pascal(t.id)}Options;`).join("\n")}\n}\n\n`;
  out += `export interface OptionField {\n  name: string;\n  flag: string;\n  kind: "string" | "integer" | "number" | "boolean" | "string[]" | "json";\n  choices?: readonly (string | number)[];\n  required: boolean;\n  description: string;\n  default?: unknown;\n}\n\n`;
  out += `export interface ToolInfo {\n  id: ToolId;\n  /** The CLI subcommand. */\n  command: string;\n  /** The client's helper method. */\n  method: string;\n  title: string;\n  description: string;\n  scope: "tools:run" | "verify";\n  limitsClass: "light" | "heavy" | "text";\n  inputs: { kinds: readonly string[]; min: number; max: number; multi: boolean };\n  optionsNote: string;\n  options: readonly OptionField[];\n}\n\n`;
  out += `export const TOOLS: readonly ToolInfo[] = ${JSON.stringify(toolMeta, null, 2)};\n`;
  files["packages/sdk-js/src/generated/tools.ts"] = out;
}

{
  let out = tsHead + "\n";
  for (const [name, s] of Object.entries(schemas)) {
    if (name.startsWith("JobOptions_")) continue;
    out += `${jsdoc(s.description)}export type ${SCHEMA_NAME[name] ?? name} = ${tsType(s)};\n\n`;
  }
  out += `/** Every operation of the API: operationId -> method and path (relative to the API base). */\nexport const ENDPOINTS = ${JSON.stringify(sortedEndpoints, null, 2)} as const;\nexport type OperationId = keyof typeof ENDPOINTS;\n`;
  files["packages/sdk-js/src/generated/api.ts"] = out;
}

{
  let out = tsHead + `import type { ToolId, ToolOptionsMap } from "./tools.js";\nimport type { FileInput, RunOptions, RunResult } from "../types.js";\n\n`;
  out += `/** One typed method per tool, made from the manifest. Each uploads, runs the job, waits and returns the result. */\nexport abstract class ToolMethods {\n  abstract run<T extends ToolId>(tool: T, inputs: FileInput[], options?: ToolOptionsMap[T], runOptions?: RunOptions): Promise<RunResult>;\n\n`;
  for (const t of tools) {
    const doc = jsdoc(`${t.title}. ${t.description}`, "  ");
    const O = `ToolOptionsMap[${JSON.stringify(t.id)}]`;
    const hasRequired = (schemas[`JobOptions_${t.id}`].required ?? []).length > 0;
    if (t.inputs.min === 0) {
      out += `${doc}  ${camel(methodName(t.id))}(options: ${O} & { file?: FileInput }, runOptions?: RunOptions): Promise<RunResult> {\n    const { file, ...rest } = options;\n    return this.run(${JSON.stringify(t.id)}, file === undefined ? [] : [file], rest as ${O}, runOptions);\n  }\n\n`;
    } else if (t.inputs.multi) {
      out += `${doc}  ${camel(methodName(t.id))}(files: FileInput[], options${hasRequired ? "" : "?"}: ${O}, runOptions?: RunOptions): Promise<RunResult> {\n    return this.run(${JSON.stringify(t.id)}, files, options, runOptions);\n  }\n\n`;
    } else {
      out += `${doc}  ${camel(methodName(t.id))}(file: FileInput, options${hasRequired ? "" : "?"}: ${O}, runOptions?: RunOptions): Promise<RunResult> {\n    return this.run(${JSON.stringify(t.id)}, [file], options, runOptions);\n  }\n\n`;
    }
  }
  out = out.replace(/\n\n$/, "\n") + "}\n";
  files["packages/sdk-js/src/generated/helpers.ts"] = out;
}

files["packages/sdk-js/src/generated/version.ts"] = `${tsHead}\nexport const SDK_VERSION = ${JSON.stringify(jsVersion)};\n`;

// ---------------------------------------------------------------- Python

function pyType(s) {
  if (!s || typeof s !== "object") return "Any";
  if (s.const !== undefined) return `Literal[${JSON.stringify(s.const)}]`;
  if (s.enum) return `Literal[${s.enum.map((v) => JSON.stringify(v)).join(", ")}]`;
  const alts = s.anyOf ?? s.oneOf;
  if (alts) {
    if (alts.every((a) => a.const !== undefined)) return `Literal[${alts.map((a) => JSON.stringify(a.const)).join(", ")}]`;
    return `Union[${alts.map(pyType).join(", ")}]`;
  }
  switch (s.type) {
    case "string": return "str";
    case "integer": return "int";
    case "number": return "float";
    case "boolean": return "bool";
    case "array": return `List[${pyType(s.items)}]`;
    case "object": return "Dict[str, Any]";
    default: return "Any";
  }
}
const pyStr = (v) => JSON.stringify(v);
/** JSON -> a Python literal (True/False/None). */
function pyLiteral(v, indent = "") {
  if (v === null || v === undefined) return "None";
  if (v === true) return "True";
  if (v === false) return "False";
  if (typeof v === "number" || typeof v === "string") return JSON.stringify(v);
  const inner = indent + "    ";
  if (Array.isArray(v)) {
    if (!v.length) return "[]";
    if (v.every((x) => typeof x !== "object" || x === null)) return `[${v.map((x) => pyLiteral(x)).join(", ")}]`;
    return `[\n${v.map((x) => `${inner}${pyLiteral(x, inner)},`).join("\n")}\n${indent}]`;
  }
  const keys = Object.keys(v);
  if (!keys.length) return "{}";
  return `{\n${keys.map((k) => `${inner}${JSON.stringify(k)}: ${pyLiteral(v[k], inner)},`).join("\n")}\n${indent}}`;
}
const pyDoc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');

{
  let out = `# ${HEADER_NOTE}\n# fmt: off\n"""The generated part of the KovaPDF SDK: tools, their options and the API's endpoints."""\n\n`;
  out += `from typing import Any, Dict, List, Literal, Optional, Sequence, TypedDict, Union\n\n`;
  out += `SDK_VERSION = ${pyStr(pyVersion)}\nATTRIBUTION = ${pyStr(manifest.attribution)}\nSITE_URL = ${pyStr(manifest.server.website)}\nAPI_BASE = ${pyStr(manifest.server.apiBase)}\n\n`;
  out += `TOOL_IDS = (${tools.map((t) => pyStr(t.id)).join(", ")},)\nToolId = Literal[${tools.map((t) => pyStr(t.id)).join(", ")}]\n\n`;
  for (const t of tools) {
    const sch = schemas[`JobOptions_${t.id}`];
    const props = Object.entries(sch.properties ?? {});
    out += `\nclass ${pascal(t.id)}Options(TypedDict, total=False):\n    """Options of ${t.id} (${pyDoc(t.title)}): ${pyDoc(t.optionsNote)}"""\n\n`;
    out += props.length ? props.map(([k, s]) => `    ${k}: ${pyType(s)}\n`).join("") : "    pass\n";
    out += "\n";
  }
  out += `\nTOOLS: List[Dict[str, Any]] = ${pyLiteral(toolMeta.map((t) => ({ ...t, method: methodName(t.id) })))}\n\n`;
  out += `ENDPOINTS: Dict[str, Dict[str, Any]] = ${pyLiteral(sortedEndpoints)}\n\n`;

  // Typed methods, one per tool.
  out += `\nclass ToolMethods:\n    """One method per tool, made from the manifest. Each uploads, runs the job, waits and returns the result."""\n\n`;
  out += `    def run(self, tool: str, inputs: Sequence[Any] = (), options: Optional[Dict[str, Any]] = None, *, timeout: Optional[float] = None, save_to: Optional[str] = None) -> Any:  # pragma: no cover\n        raise NotImplementedError\n\n`;
  for (const t of tools) {
    const sch = schemas[`JobOptions_${t.id}`];
    const req = new Set(sch.required ?? []);
    const props = Object.entries(sch.properties ?? {});
    const params = [];
    let inputsExpr;
    if (t.inputs.min === 0) { params.push("file: Any = None"); inputsExpr = "[] if file is None else [file]"; }
    else if (t.inputs.multi) { params.push("files: Sequence[Any]"); inputsExpr = "list(files)"; }
    else { params.push("file: Any"); inputsExpr = "[file]"; }
    const kw = [];
    for (const [k, s] of props) kw.push(req.has(k) ? `${snake(k)}: ${pyType(s)}` : `${snake(k)}: Optional[${pyType(s)}] = None`);
    kw.push("timeout: Optional[float] = None", "save_to: Optional[str] = None");
    const sig = `self, ${params.join(", ")}, *, ${kw.join(", ")}`;
    const optsDict = props.length ? `{${props.map(([k]) => `${pyStr(k)}: ${snake(k)}`).join(", ")}}` : "{}";
    out += `    def ${methodName(t.id)}(${sig}) -> Any:\n        """${pyDoc(t.title)}. ${pyDoc(t.description)}"""\n`;
    out += `        options = {k: v for k, v in ${optsDict}.items() if v is not None}\n`;
    out += `        return self.run(${pyStr(t.id)}, ${inputsExpr}, options, timeout=timeout, save_to=save_to)\n\n`;
  }
  out = out.replace(/\n+$/, "\n");
  files["packages/sdk-python/src/kovapdf/_generated.py"] = out;
}

// ---------------------------------------------------------------- write or check

const check = process.argv.includes("--check");
const drift = [];
for (const [rel, content] of Object.entries(files)) {
  const file = path.join(ROOT, rel);
  const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (now === content) continue;
  if (check) drift.push(rel);
  else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (check && drift.length) {
  console.error(`These SDK files differ from the manifest and the OpenAPI file. Run: node packages/sdk-js/scripts/generate.mjs\n${drift.map((d) => `  ${d}`).join("\n")}`);
  process.exit(1);
}
if (check) console.log("sdk: every generated file matches the manifest and the OpenAPI file");
